const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

function step(
  label: string,
  kind: "plan" | "tool" | "validate" | "fix" | "done" | "error",
  status: "running" | "done" | "error",
  detail?: string,
  id = randomUUID(),
): AgentEvent {
  return { type: "trace", step: { id, label, kind, status, detail } };
}

async function* streamText(text: string): AsyncGenerator<AgentEvent> {
  const tokens = text.match(/\S+\s*/g) ?? [text];
  for (const t of tokens) {
    yield { type: "delta", delta: t };
    await sleep(8);
  }
}

function titleCase(s: string) {
  return s.replace(/\b\w/g, (c) => c.toUpperCase());
}

function projectName(prompt: string) {
  const cleaned = prompt
    .replace(/^(please\s+)?(build|create|make|generate|design|write)\s+(me\s+)?(a|an|the)?\s*/i, "")
    .split(/[.,\n]/)[0]
    .trim();
  return titleCase(cleaned.split(/\s+/).slice(0, 5).join(" ") || "New Project");
}

