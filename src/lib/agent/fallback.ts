export async function* runFallbackAgent(
  conversationId: string,
  prompt: string,
  demoNotice: string,
): AsyncGenerator<AgentEvent> {
  if (!isBuildRequest(prompt)) {
    yield* streamText(
      `${demoNotice}\n\nI can still talk things through. You asked:\n\n> ${prompt.trim()}\n\n` +
        "Here's how I'd approach it:\n\n" +
        "1. Clarify the outcome you want in one sentence.\n" +
        "2. Break it into the smallest steps that each produce something testable.\n" +
        "3. Build the thinnest end-to-end slice first, then deepen it.\n\n" +
        "Add a `DEEPSEEK_API_KEY` to your environment and I'll answer with the real model, " +
        "with full reasoning and tool use.",
    );
    return;
  }

  const { name, files } = buildFiles(prompt);

  const planId = randomUUID();
  yield step("Planning approach", "plan", "running", undefined, planId);
  await sleep(300);
  yield step("Planned 4 steps", "plan", "done", "scaffold → style → behaviour → validate", planId);

  yield* streamText(
    `${demoNotice}\n\n**Plan**\n\n1. Scaffold \`index.html\` with semantic sections for ${name}.\n` +
      "2. Write `styles.css` with design tokens and a mobile-first responsive layout.\n" +
      "3. Add `app.js` for the interactive list with localStorage persistence.\n" +
      "4. Run a build check and write the README.\n\n",
  );

  for (const file of files) {
    const id = randomUUID();
    yield step(`Creating file: ${file.path}`, "tool", "running", undefined, id);
    const res = await runTool(conversationId, "file_write", file);
    await sleep(160);
    yield step(res.label, "tool", res.ok ? "done" : "error", res.detail, id);
    if (res.terminal) yield { type: "terminal", lines: res.terminal };
    yield { type: "files" };
  }

  const vid = randomUUID();
  yield step("Running build check", "validate", "running", undefined, vid);
  const build = await runTool(conversationId, "run_command", { command: "build" });
  await sleep(250);
  yield step("Build check", "validate", build.ok ? "done" : "error", build.detail, vid);
  if (build.terminal) yield { type: "terminal", lines: build.terminal };

  yield step("Task complete", "done", "done", `${files.length} files`);

  yield* streamText(
    `**Done — ${name} is built.**\n\n` +
      files.map((f) => `- \`${f.path}\``).join("\n") +
      "\n\nOpen the **Workspace** panel on the right: *Preview* renders it live, *Code* shows every file, " +
      "*Terminal* has the build log. Use **Export ZIP** to download it.\n\n" +
      "Next steps I'd suggest:\n" +
      "1. Add a dark mode toggle driven by `prefers-color-scheme`.\n" +
      "2. Persist items to an API instead of localStorage.\n" +
      "3. Add keyboard shortcuts for add/complete.\n",
  );
}
